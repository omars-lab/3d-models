"""Write the Lebanon flag cedar's outer outline as an OpenSCAD polygon.

OpenSCAD 2021.01 imports the green path of Flag_of_Lebanon.svg (Wikimedia, public domain) into a
shape Bambu Studio refuses to slice once it is cut out of the stencil card. This flattens the
path's first subpath (the outer edge; the other 21 are the white details inside the cedar, left
out so the stencil hole is one opening), cleans it into one valid polygon, and writes it in SVG px
with y up, centered on the flag's middle (1440, 960).

    uv run --with svgelements --with shapely python src/Stencils/make_cedar_outline.py
"""

import re
from pathlib import Path

from shapely.geometry import Polygon
from svgelements import Path as SvgPath

HERE = Path(__file__).parent
FLAG_MIDDLE = (1440, 960)
STEP_PX = 2  # flattening step along each curve
SIMPLIFY_PX = 0.5  # 0.05 mm at Letter width; far under the 1.5 mm grow


def main() -> None:
    svg = (HERE / "Flag_of_Lebanon.svg").read_text()
    d = re.search(r'fill="#008c3e" d="([^"]+)"', svg).group(1)
    outer = next(SvgPath(d).as_subpaths())
    pts = []
    for seg in outer:
        if seg.start is None or seg.end is None:
            continue
        n = max(2, int(seg.length() / STEP_PX))
        pts += [(q.x, q.y) for q in (seg.point(i / n) for i in range(n))]
    poly = Polygon([(x - FLAG_MIDDLE[0], FLAG_MIDDLE[1] - y) for x, y in pts]).buffer(0)
    if poly.geom_type != "Polygon":
        poly = max(poly.geoms, key=lambda g: g.area)
    poly = poly.simplify(SIMPLIFY_PX).buffer(0)
    coords = list(poly.exterior.coords)[:-1]
    minx, miny, maxx, maxy = poly.bounds
    body = ",\n".join(f"  [{x:.2f}, {y:.2f}]" for x, y in coords)
    (HERE / "lebanon-cedar-outline.scad").write_text(
        "// Generated by make_cedar_outline.py from Flag_of_Lebanon.svg; do not edit.\n"
        f"// SVG px, y up, flag middle at the origin. {len(coords)} points,"
        f" x {minx:.1f}..{maxx:.1f}, y {miny:.1f}..{maxy:.1f}.\n"
        f"cedar_outline = [\n{body}\n];\n"
    )
    print(f"points={len(coords)} x={minx:.1f}..{maxx:.1f} y={miny:.1f}..{maxy:.1f}")


if __name__ == "__main__":
    main()
