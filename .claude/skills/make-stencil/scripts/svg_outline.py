"""Write one shape's outer outline from an SVG as an OpenSCAD polygon, for a tracing stencil.

OpenSCAD 2021.01 imports an SVG path into a shape Bambu Studio refuses to slice once it is cut out
of a stencil card (cedar-stencil-1, 2026-10-30). This flattens one path's outer edge (its first
subpath by default; the others are usually details inside the shape, left out so the stencil hole
is one opening), cleans it into one valid polygon, and writes it in SVG px with y up, centered on
the SVG's middle unless --origin says otherwise. The .scad file then scales it to millimetres.

    uv run --with svgelements --with shapely python .claude/skills/make-stencil/scripts/svg_outline.py \
        src/Stencils/Flag_of_Lebanon.svg --fill "#008c3e" --var cedar_outline \
        --out src/Stencils/lebanon-cedar-outline.scad
"""

import argparse
import re
from pathlib import Path

from shapely.geometry import Polygon
from svgelements import Path as SvgPath

STEP_PX = 2  # flattening step along each curve
SIMPLIFY_PX = 0.5  # 0.05 mm at Letter width for the cedar; far under the 1.5 mm grow


def svg_middle(svg: str) -> tuple[float, float]:
    box = re.search(r'viewBox="([-\d.\s,]+)"', svg)
    if box:
        x, y, w, h = (float(v) for v in re.split(r"[\s,]+", box.group(1).strip()))
        return x + w / 2, y + h / 2
    w = re.search(r'\bwidth="([\d.]+)', svg)
    h = re.search(r'\bheight="([\d.]+)', svg)
    if not (w and h):
        raise SystemExit("no viewBox or width/height in the SVG: pass --origin X,Y")
    return float(w.group(1)) / 2, float(h.group(1)) / 2


def path_d(svg: str, fill: str | None, path_id: str | None) -> str:
    if path_id:
        m = re.search(rf'<path[^>]*\bid="{re.escape(path_id)}"[^>]*>', svg)
    elif fill:
        m = re.search(rf'<path[^>]*\bfill="{re.escape(fill)}"[^>]*>', svg, re.IGNORECASE)
    else:
        raise SystemExit("name the path: --fill <color> or --id <path id>")
    if not m:
        raise SystemExit(f"no <path> with {'id ' + path_id if path_id else 'fill ' + fill}")
    d = re.search(r'\bd="([^"]+)"', m.group(0))
    if not d:
        raise SystemExit("the path has no d attribute")
    return d.group(1)


def outline(d: str, subpath: int, origin: tuple[float, float]) -> Polygon:
    outer = list(SvgPath(d).as_subpaths())[subpath]
    pts = []
    for seg in outer:
        if seg.start is None or seg.end is None:
            continue
        n = max(2, int(seg.length() / STEP_PX))
        pts += [(q.x, q.y) for q in (seg.point(i / n) for i in range(n))]
    poly = Polygon([(x - origin[0], origin[1] - y) for x, y in pts]).buffer(0)
    if poly.geom_type != "Polygon":
        poly = max(poly.geoms, key=lambda g: g.area)
    return poly.simplify(SIMPLIFY_PX).buffer(0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("svg", type=Path)
    ap.add_argument("--fill", help="pick the first <path> with this fill color")
    ap.add_argument("--id", dest="path_id", help="pick the <path> with this id")
    ap.add_argument("--subpath", type=int, default=0, help="which subpath is the outer edge (default 0)")
    ap.add_argument("--origin", help="X,Y in SVG px to put at the origin (default the SVG's middle)")
    ap.add_argument("--var", required=True, help="the OpenSCAD variable name, e.g. cedar_outline")
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    svg = a.svg.read_text()
    origin = tuple(float(v) for v in a.origin.split(",")) if a.origin else svg_middle(svg)
    poly = outline(path_d(svg, a.fill, a.path_id), a.subpath, origin)
    coords = list(poly.exterior.coords)[:-1]
    minx, miny, maxx, maxy = poly.bounds
    body = ",\n".join(f"  [{x:.2f}, {y:.2f}]" for x, y in coords)
    a.out.write_text(
        f"// Generated by the make-stencil skill's svg_outline.py from {a.svg.name}; do not edit.\n"
        f"// SVG px, y up, ({origin[0]:g}, {origin[1]:g}) at the origin. {len(coords)} points,"
        f" x {minx:.1f}..{maxx:.1f}, y {miny:.1f}..{maxy:.1f}.\n"
        f"{a.var} = [\n{body}\n];\n"
    )
    print(f"points={len(coords)} x={minx:.1f}..{maxx:.1f} y={miny:.1f}..{maxy:.1f} out={a.out}")


if __name__ == "__main__":
    main()
